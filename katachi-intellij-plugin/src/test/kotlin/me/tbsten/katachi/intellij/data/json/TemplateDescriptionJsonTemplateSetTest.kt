package me.tbsten.katachi.intellij.data.json

import me.tbsten.katachi.intellij.model.ParameterModel
import me.tbsten.katachi.intellij.model.SetArgModel
import me.tbsten.katachi.intellij.model.TemplateModel
import me.tbsten.katachi.intellij.model.TemplateUnavailability
import me.tbsten.katachi.intellij.model.groupOrderOf
import me.tbsten.katachi.intellij.testing.ContractFixtures
import me.tbsten.katachi.intellij.testing.DefinitionFixtures
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test
import java.nio.file.Paths

/**
 * `templateSets[]` / `templateSetDetails[]` of `templateDescription.json` (katachi's own
 * `synthetic-template-set.json`, generated by `:katachi:test`): a set is one more row of the list.
 */
class TemplateDescriptionJsonTemplateSetTest {
    private val rows = ContractFixtures.templates("synthetic-template-set")
    private val sets = rows.filter { it.set != null }

    private fun row(specifier: String): TemplateModel = rows.single { it.template == specifier }

    private fun parse(json: String) = parseTemplateDescriptionJson(json, Paths.get("/inline.json"))

    @Test
    fun `組の行はテンプレートの行の後ろに組の宣言の順で並ぶ`() {
        assertEquals(
            listOf("feature.FeatureScreen", "feature.FeatureViewModel", "shared.Logger", "ui.Screen", "Starter", "feature.NewFeature", "feature.Broken"),
            rows.map { it.template },
        )
        assertEquals(listOf("Starter", "feature.NewFeature", "feature.Broken"), sets.map { it.template })
        assertTrue(rows.take(4).all { it.set == null })
    }

    @Test
    fun `組の行の要約と詳細は組のものでgroupPathは組のgroupになる`() {
        val set = row("feature.NewFeature")
        assertEquals("新しい機能", set.title)
        assertEquals("feature.NewFeature", set.roleName)
        assertEquals("feature", set.groupPath)
        assertEquals("", row("Starter").groupPath)
        assertEquals(listOf("feature", "name", "withState"), set.summary.parameterNames)
        assertEquals(emptyList<String>(), set.summary.captureNames)
        assertEquals("NewFeature", set.set?.name)
        val detail = requireNotNull(set.detail)
        assertEquals(listOf("feature", "name", "withState"), detail.parameters.map { it.name })
        assertTrue(detail.parameters[2] is ParameterModel.BooleanParam)
        assertEquals(emptyList<Any>(), detail.captures)
        assertEquals(emptyList<Any>(), detail.branches)
        assertTrue(detail.exampleCommand.contains("--arg template=feature.NewFeature"))
        assertNull(set.unavailability)
    }

    @Test
    fun `組の行のファイルは全メンバのファイルを書いた順に連結し引数の対応を持つ`() {
        val set = row("feature.NewFeature")
        val members = requireNotNull(set.set).members
        assertEquals(listOf("feature.FeatureScreen", "feature.FeatureViewModel", "shared.Logger", "ui.Screen"), members.map { it.template })
        assertEquals(listOf("${'$'}{name}Screen.kt", "${'$'}{name}ViewModel.kt", "Logger.kt", "${'$'}{name}Page.kt"), set.detail!!.files.map { it.fileName })
        val viewModelArgs = members[1].args
        assertEquals(listOf("name", "withState"), viewModelArgs.map { it.name })
        assertEquals(listOf(true, false), viewModelArgs.map { it.isCapture })
        assertEquals(listOf("name", "withState"), viewModelArgs.map { it.parameter })
        assertNull(members[2].args.single().parameter)
    }

    @Test
    fun `組の行のファイルのpatternはメンバのファイルのpathになる`() {
        val files = row("feature.NewFeature").detail!!.files
        assertEquals("src/main/kotlin/feature/${'$'}{name}/${'$'}{name}Screen.kt", files[0].pattern)
        assertEquals(files[0].path, files[0].pattern)
        assertEquals("src/main/kotlin/shared/Logger.kt", files[2].pattern)
    }

    @Test
    fun `組のパラメータがメンバのcapture名と違ってもpatternは組のプレースホルダで埋まる`() {
        val file = """{"pattern":"a/${'$'}{name}.kt","fileName":"${'$'}{name}.kt","path":"a/${'$'}{title}.kt","captures":["name"],"parameters":[],"content":""}"""
        val json = """{"templates":[],"details":[],"modulePlacements":[],
            "templateSets":[{"templateSet":"S","name":"S","title":"S","summary":null,"groupName":null,"parameterNames":["title"],"members":["m.M"],"conflict":false}],
            "templateSetDetails":[{"templateSet":"S","name":"S","title":"S","summary":null,"groupName":null,
              "parameters":[{"name":"title","kind":"StringParameter","typeName":"String","default":null,"acceptedValues":[],"isRequired":true,"previewValue":"${'$'}{title}","previewValueSource":"Placeholder"}],
              "members":[{"template":"m.M","title":"M","args":[{"name":"name","kind":"Capture","previewValue":"${'$'}{title}","parameter":"title"}],"files":[$file]}],
              "exampleCommand":"x"}]}"""
        val files = parse(json).single().detail!!.files
        assertEquals("a/${'$'}{title}.kt", files.single().pattern)
        assertEquals("${'$'}{title}.kt", files.single().fileName)
        assertEquals(listOf("title"), files.single().captures)
    }

    @Test
    fun `モジュールのcaptureの下のメンバは組のパラメータ名に置き換えた生成先を持つ`() {
        val page = row("feature.NewFeature").detail!!.files[3]
        assertNull(page.path)
        val placement = requireNotNull(page.modulePlacement)
        assertEquals(listOf("feature"), placement.captureNames)
        assertEquals(listOf("feature/home/src/main/kotlin/${'$'}{name}Page.kt", "feature/settings/src/main/kotlin/${'$'}{name}Page.kt"), placement.modules.map { it.path })
    }

    private fun capture(name: String, value: String, parameter: String?) = SetArgModel(name, true, value, parameter)

    @Test
    fun `組のパラメータ名が違えば生成先のcapture名とプレースホルダを組の名前に置き換える`() {
        val placement = requireNotNull(row("ui.Screen").detail!!.files.single().modulePlacement)
        val renamed = requireNotNull(
            placedInSetNames(placement, listOf(capture("feature", "${'$'}{module}", "module"), capture("name", "${'$'}{page}", "page"))),
        )
        assertEquals(listOf("module"), renamed.captureNames)
        assertEquals("feature/home/src/main/kotlin/${'$'}{page}Page.kt", renamed.modules.first().path)
    }

    @Test
    fun `置き換えられないcaptureがあれば生成先を付けない`() {
        val placement = requireNotNull(row("ui.Screen").detail!!.files.single().modulePlacement)
        // 鍵の feature が組のパラメータそのままではない。
        assertNull(placedInSetNames(placement, listOf(capture("feature", "home", null), capture("name", "${'$'}{name}", "name"))))
        // パスの name に値が無い。
        assertNull(placedInSetNames(placement, listOf(capture("feature", "${'$'}{feature}", "feature"))))
    }

    @Test
    fun `名前を入れ替える置き換えは同時に行う`() {
        val placement = requireNotNull(row("ui.Screen").detail!!.files.single().modulePlacement)
        val swapped = requireNotNull(
            placedInSetNames(placement, listOf(capture("feature", "${'$'}{name}", "name"), capture("name", "${'$'}{feature}", "feature"))),
        )
        assertEquals("feature/home/src/main/kotlin/${'$'}{feature}Page.kt", swapped.modules.first().path)
    }

    private fun moduleSetJson(args: String): String {
        val file = """{"pattern":"feature/${'$'}{feature}/${'$'}{name}Page.kt","fileName":"${'$'}{name}Page.kt","path":null,"captures":["feature","name"],"parameters":[],"content":""}"""
        return """{"templates":[],"details":[],
            "modulePlacements":[{"template":"m.M","modulePattern":":feature:*","captureNames":["feature"],"modules":[
              {"values":["home"],"modulePath":":feature:home","directory":"feature/home","path":"feature/home/${'$'}{name}Page.kt"}]}],
            "templateSets":[{"templateSet":"S","name":"S","title":"S","summary":null,"groupName":null,"parameterNames":["module","title"],"members":["m.M"],"conflict":false}],
            "templateSetDetails":[{"templateSet":"S","name":"S","title":"S","summary":null,"groupName":null,
              "parameters":[],
              "members":[{"template":"m.M","title":"M","args":[$args],"files":[$file]}],
              "exampleCommand":"x"}]}"""
    }

    private fun arg(name: String, value: String, parameter: String?) =
        """{"name":"$name","kind":"Capture","previewValue":"$value","parameter":${parameter?.let { "\"$it\"" } ?: "null"}}"""

    @Test
    fun `鍵の名前が組のパラメータ名と違っても生成先は組の名前で組み立つ`() {
        val file = parse(moduleSetJson(arg("feature", "${'$'}{module}", "module") + "," + arg("name", "${'$'}{title}", "title")))
            .single().detail!!.files.single()
        val placement = requireNotNull(file.modulePlacement)
        assertEquals(listOf("module"), placement.captureNames)
        assertEquals("feature/home/${'$'}{title}Page.kt", placement.modules.single().path)
        assertEquals("feature/${'$'}{module}/${'$'}{title}Page.kt", file.pattern)
        assertEquals("${'$'}{title}Page.kt", file.fileName)
        assertEquals(listOf("module", "title"), file.captures)
    }

    @Test
    fun `ファイル名のcaptureに式や定数を渡しても生成先にその値が入る`() {
        val file = parse(moduleSetJson(arg("feature", "${'$'}{module}", "module") + "," + arg("name", "${'$'}{title}Main", null)))
            .single().detail!!.files.single()
        assertEquals("feature/home/${'$'}{title}MainPage.kt", file.modulePlacement!!.modules.single().path)
        assertEquals("feature/${'$'}{module}/${'$'}{title}MainPage.kt", file.pattern)
        assertEquals("${'$'}{title}MainPage.kt", file.fileName)
        val constant = parse(moduleSetJson(arg("feature", "${'$'}{module}", "module") + "," + arg("name", "Home", null)))
            .single().detail!!.files.single()
        assertEquals("feature/home/HomePage.kt", constant.modulePlacement!!.modules.single().path)
    }

    @Test
    fun `鍵が組のパラメータそのままでなければ生成先を付けずpatternももとのまま`() {
        val file = parse(moduleSetJson(arg("feature", "home", null) + "," + arg("name", "${'$'}{title}", "title")))
            .single().detail!!.files.single()
        assertNull(file.modulePlacement)
        assertEquals("feature/${'$'}{feature}/${'$'}{name}Page.kt", file.pattern)
        assertEquals("${'$'}{name}Page.kt", file.fileName)
    }

    @Test
    fun `conflictの組は詳細が無くチェックできない`() {
        val broken = row("feature.Broken")
        assertNull(broken.detail)
        assertEquals(TemplateUnavailability.PreviewFailed, broken.unavailability)
        assertEquals("Broken", broken.set?.name)
    }

    @Test
    fun `templateSetsの無いJSONは組が0行で他は今のまま`() {
        for (name in listOf("arch-a", "arch-b", "capture", "sample-jvm", "sample-android-with-captures", "sample-kmp")) {
            assertTrue(name, ContractFixtures.templates(name).none { it.set != null })
        }
        val text = ContractFixtures.json("synthetic-template-set")
        val without = text.substring(0, text.indexOf("\"templateSets\"")).trimEnd().removeSuffix(",") + "\n}"
        assertEquals(rows.take(4), parse(without))
    }

    @Test
    fun `templateSetDetailsの型違いは位置つきの版の不一致にする`() {
        val json = """{"templates":[],"details":[],"templateSets":[],
            "templateSetDetails":[{"templateSet":"A","parameters":[],"members":"x","exampleCommand":""}]}"""
        val failure = assertThrows(KatachiIncompatibleTemplateJsonException::class.java) { parse(json) }
        assertTrue(failure.message, failure.message!!.contains("templateSetDetails[0].members"))
    }

    @Test
    fun `定義JSONのtemplatesの中の組も読める`() {
        val definition = DefinitionFixtures.parsed("synthetic-definition-template-set")
        assertEquals(listOf("Starter", "feature.NewFeature", "feature.Broken"), definition.templates.filter { it.set != null }.map { it.template })
    }

    @Test
    fun `定義JSONのtemplatesの中のtemplateSetDetailsの型違いはtemplates配下の位置で報告される`() {
        val text = DefinitionFixtures.definitionText("synthetic-definition-template-set")
        val from = text.indexOf("\"templateSetDetails\"")
        val broken = text.substring(0, from) + text.substring(from).replaceFirst("\"members\": [", "\"members\": \"x\", \"ignored\": [")
        val failure = assertThrows(KatachiIncompatibleDefinitionJsonException::class.java) {
            parseDefinitionJson(broken, DefinitionFixtures.path("synthetic-definition-template-set"))
        }
        assertTrue(failure.location, failure.location.contains("templates.templateSetDetails[0].members"))
    }

    @Test
    fun `組の行はgroupの見出しの下でテンプレートの後に宣言の順で並ぶ`() {
        val ordered = groupOrderOf(rows).map { it.template }
        assertEquals(
            listOf("Starter", "feature.FeatureScreen", "feature.FeatureViewModel", "feature.NewFeature", "feature.Broken", "shared.Logger", "ui.Screen"),
            ordered,
        )
    }
}
