/**
 * `definition.json` into the model (design 1.x): what is read, what is ignored, and what is refused.
 *
 * The files read are the ones katachi wrote (`synthetic-definition-*.json`, generated by `:katachi:test`):
 * `structure` (captures, templates), `basic` (the constraints and their ranges), `explained` (`fileDeclarations`).
 * `handwritten-definition-future.json` holds only what katachi's own tests cannot write: the Konsist backends, and
 * values a newer katachi might add. `handwritten-module-capture-definition.json` is `structure` as katachi 0.3
 * wrote it, when `other.Wildcard` was below `":feature:*".module { }`: kept by hand since katachi 0.4 removed
 * `.module { }`, so that module keys and the entries `module { }` injected stay readable. The refusals patch the
 * text of a generated file.
 */
class DefinitionJsonParserTest {
    private val name = "synthetic-definition-structure"
    private val text = DefinitionFixtures.definitionText(name)
    private val parsed = DefinitionFixtures.parsed(name)
    private val definition = parsed.definition
    private val basic = DefinitionFixtures.definition("synthetic-definition-basic")
    private val explained = DefinitionFixtures.definition("synthetic-definition-explained")
    private val future = DefinitionFixtures.definition("handwritten-definition-future")
    private val moduleCapture = DefinitionFixtures.definition("handwritten-module-capture-definition")

    private fun parse(json: String) = parseDefinitionJson(json, DefinitionFixtures.path(name))

    private inline fun <reified T : Throwable> failureOf(json: String): T =
        runCatching { parse(json) }.exceptionOrNull() as? T ?: throw AssertionError("expected ${T::class.simpleName}")

    @Test
    fun `contract の definition fixture はすべて読め layout の添字は並びと一致し制約は存在する entry を指す`() {
        val names = DefinitionFixtures.definitionNames()
        assertTrue(names.containsAll(listOf(name, "synthetic-definition-basic", "synthetic-definition-explained", "handwritten-definition-future")))
        for (fixture in names) {
            val model = DefinitionFixtures.definition(fixture)
            assertTrue("$fixture has roles", model.roles.isNotEmpty())
            for (role in model.roles) {
                assertEquals("$fixture ${role.qualifiedName}", role.layout.indices.toList(), role.layout.map { it.index })
                for (constraint in role.constraints) {
                    assertTrue("$fixture ${role.qualifiedName}", constraint.entryIndices.all { it in role.layout.indices })
                }
            }
        }
    }

    @Test
    fun `トップレベルの項目が読める`() {
        assertEquals(Paths.get("/repo"), definition.projectRoot)
        assertEquals("0.3.0", definition.katachiVersion)
        assertEquals(Instant.parse("2026-10-04T00:30:12Z"), definition.generatedAt)
        assertEquals(ArchitectureModel(DeclarationSiteRef("IdePluginSyntheticSpecSupport.kt", 51), "gitTracked", null), definition.architecture)
        assertTrue(definition.architecture.isGitTracked)
        assertEquals(listOf("a", "a.b", "a.b.c", "other"), definition.groups.map { it.qualifiedName })
        assertEquals(
            listOf("AllTypes", "Counter", "a.Shallow", "a.b.Middle", "a.b.c.Deep", "other.Broken", "other.Wildcard"),
            definition.roles.map { it.qualifiedName },
        )
        assertTrue(!basic.architecture.isGitTracked)
    }

    @Test
    fun `group と role のメタデータは null と false と true を区別して読む`() {
        assertEquals("Domain", basic.groups.single().title)
        assertEquals(listOf<Boolean?>(null, false), basic.roles.filter { it.qualifiedName.startsWith("domain.") }.map { it.documented })
        assertEquals(listOf<Boolean?>(null, true, false), future.groups.map { it.documented })
        val useCase = basic.roles.single { it.qualifiedName == "domain.UseCase" }
        assertEquals(listOf("domain"), useCase.groupPath)
        assertEquals("Use case", useCase.title)
        assertEquals("One behaviour of a screen", useCase.summary)
        assertEquals(DeclarationSiteRef("DescribeDefinitionSpecSupport.kt", 93), useCase.declaredAt)
    }

    @Test
    fun `layout の entry は glob と kind と取り込んだファイルを持つ`() {
        val middle = definition.roles.single { it.qualifiedName == "a.b.Middle" }
        val entry = middle.layout[5]
        assertEquals("src/main/kotlin/a/b/*", entry.pattern)
        assertEquals(LayoutEntryKind.File, entry.kind)
        assertEquals(5, entry.index)
        assertEquals(listOf("name", 5, 0, null), entry.captures.single().let { listOf(it.name, it.segmentIndex, it.wildcardIndex, it.transform) })
        assertEquals("a.b.Middle", entry.template?.specifier)
        assertEquals(listOf("src/main/kotlin/a/b/Middle.kt"), entry.matchedFiles)
        assertEquals(1, entry.matchedCount)
        assertEquals(DeclarationSiteRef("IdePluginSyntheticSpecSupport.kt", 108), middle.declaredAt)
        val directory = middle.layout[0]
        assertNull(directory.matchedCount)
        assertEquals(LayoutEntryKind.Directory, directory.kind)
        assertEquals("Behavior for each screen", future.roles.first().layout[0].description)
    }

    @Test
    fun `module の key は module のパスと capture の名前を持ち ファイルの無い entry は件数 0`() {
        val wildcard = moduleCapture.roles.single { it.qualifiedName == "other.Wildcard" }
        val home = wildcard.layout[1]
        assertEquals(":feature:home", home.modulePath)
        assertEquals("", home.pathInModule)
        assertEquals(listOf("feature"), home.moduleCapture?.names)
        assertEquals(":feature:*", home.moduleCapture?.pattern)
        val settingsScreen = wildcard.layout.last()
        assertEquals(":feature:settings", settingsScreen.modulePath)
        assertEquals(0, settingsScreen.matchedCount)
        assertEquals(emptyList<String>(), settingsScreen.matchedFiles)
        assertEquals(1, wildcard.layout[7].matchedCount)
    }

    @Test
    fun `制約は backend と range と被覆と entry の添字を持つ`() {
        val useCase = basic.roles.single { it.qualifiedName == "domain.UseCase" }.constraints.single()
        assertEquals("does nothing", useCase.name)
        assertEquals(ConstraintBackend.Custom, useCase.backend)
        assertEquals("me.tbsten.katachi.test.ide.AcceptEverything", useCase.checkClass)
        assertEquals(ConstraintRange.Subtree, useCase.range)
        assertEquals(listOf(6), useCase.entryIndices)
        assertEquals(listOf("core/domain/src/main/kotlin/useCase"), useCase.anchors)
        assertEquals(listOf("core/domain/src/main/kotlin/useCase/*UseCase.kt"), useCase.coverage.files)
        assertNull(useCase.fileDeclarations)
        val (whole, direct) = basic.roles.single { it.qualifiedName == "domain.Model" }.constraints
        assertEquals(ConstraintRange.Subtree, whole.range)
        assertEquals(listOf(5, 7), whole.entryIndices)
        assertEquals(ConstraintRange.DirectOnly, direct.range)
        assertEquals(listOf("core/domain/src/main/kotlin/model"), direct.coverage.anyFileDirectories)
        assertEquals(DeclarationSiteRef("DescribeDefinitionSpecSupport.kt", 111), direct.declaredAt)
        assertNull(whole.layoutPath)
        assertEquals("core/domain/src/main/kotlin/model", direct.layoutPath)
    }

    @Test
    fun `Konsist の backend は konsist と ktFileContent として読め 名前の無い制約は name が null`() {
        val (konsist, ktFile) = future.roles.first().constraints
        assertEquals(ConstraintBackend.Konsist, konsist.backend)
        assertEquals(ConstraintBackend.KtFileContent, ktFile.backend)
        assertEquals(ConstraintRange.Subtree, konsist.range)
        assertEquals(listOf(1), konsist.entryIndices)
        assertNull(konsist.fileDeclarations)
        assertNull(ktFile.name)
        val direct = future.roles[1].constraints.first()
        assertEquals(ConstraintRange.DirectOnly, direct.range)
        assertEquals(listOf("feature/*/ui"), direct.coverage.anyFileDirectories)
    }

    @Test
    fun `宣言の説明が宣言ごとの判定と許可元の行つきで読める`() {
        val explaining = explained.roles.single { it.qualifiedName == "Service" }.constraints.first().fileDeclarations
            ?: throw AssertionError("no fileDeclarations")
        assertEquals(
            listOf("src/service/Broken.kt", "src/service/HealthService.kt", "src/service/UserServiceBad.kt"),
            explaining.map { it.file },
        )
        val (broken, healthy, bad) = explaining
        assertTrue(!broken.declarationsChecked)
        assertEquals("IllegalStateException: no rules for Broken", broken.unexplainedReason)
        assertEquals(emptyList<Any>(), broken.declarations)
        assertTrue(healthy.declarationsChecked)
        val health = healthy.declarations.single()
        assertEquals(DeclarationVerdict.Allowed, health.verdict)
        assertEquals(SourceDeclarationKind.Class, health.kind)
        assertEquals(3, health.line)
        assertEquals(DeclarationSiteRef("ExplainingRole.kt", 21), health.rules.single().declaredAt)
        assertEquals(DeclarationVerdict.Unexpected, bad.declarations.single().verdict)
        assertEquals(SourceDeclarationKind.Fun, bad.declarations.single().kind)
        assertEquals("class UserService", bad.missing.single().text)
        assertEquals(DeclarationSiteRef("ExplainingRole.kt", 21), bad.missing.single().declaredAt)
        assertNull(health.difference)
        // The constraint that does not explain has none, and the one that threw is a `problem`, not an error.
        assertNull(explained.roles.single { it.qualifiedName == "Thrower" }.constraints.single().fileDeclarations)
    }

    @Test
    fun `Mismatched の差と 許可元の無い足りない宣言も読める`() {
        val files = future.roles.first().constraints[1].fileDeclarations ?: throw AssertionError("no fileDeclarations")
        assertEquals(2, files.size)
        val first = files.first()
        assertEquals(
            listOf(DeclarationVerdict.Allowed, DeclarationVerdict.Unexpected, DeclarationVerdict.Mismatched),
            first.declarations.map { it.verdict },
        )
        assertEquals(listOf(SourceDeclarationKind.Class, SourceDeclarationKind.Fun, SourceDeclarationKind.Val), first.declarations.map { it.kind })
        assertEquals("modifiers: expected private", first.declarations[2].difference)
        assertEquals("object Companion", first.missing.single().text)
        assertNull(first.missing.single().declaredAt)
        assertEquals("IllegalStateException: boom", files[1].unexplainedReason)
    }

    @Test
    fun `知らない kind と backend と range は未知の値として残り全体は読める`() {
        assertEquals(LayoutEntryKind.Unknown("Hologram"), future.roles[2].layout[3].kind)
        val newer = future.roles[1].constraints[1]
        assertEquals(ConstraintBackend.Unknown("hologram"), newer.backend)
        assertEquals(ConstraintRange.Unknown("Teleport"), newer.range)
        assertEquals("hologram", newer.backend.jsonName)
        assertNull(newer.declaredAt)
    }

    @Test
    fun `problems は種類と文面を読み知らない種類は Unknown にして元の名前を残す`() {
        assertEquals(listOf(DefinitionProblemKind.TemplatePreviewFailed, DefinitionProblemKind.TemplatePreviewFailed), definition.problems.map { it.kind })
        assertEquals(listOf("a.b.Middle", "other.Broken"), definition.problems.map { it.detail })
        assertEquals(listOf(DefinitionProblemKind.ExplanationFailed), explained.problems.map { it.kind })
        assertEquals("Thrower", explained.problems.single().detail)
        assertEquals(listOf(DefinitionProblemKind.ExplanationTruncated, DefinitionProblemKind.Unknown), future.problems.map { it.kind })
        assertEquals(listOf("ExplanationTruncated", "FutureKind"), future.problems.map { it.kindName })
        assertEquals("x", future.problems[1].detail)
        assertEquals(emptyList<Any>(), basic.problems)
    }

    @Test
    fun `problems の declaredAt と exception と 組の失敗の種類を読み 無ければ null`() {
        val basicText = DefinitionFixtures.definitionText("synthetic-definition-basic")
        assertTrue("the fixture ends with an empty problems list", basicText.contains("\"problems\": []"))
        val withSites = basicText.replace(
            "\"problems\": []",
            """"problems": [
              { "kind": "TemplateSetPreviewFailed", "message": "m", "detail": "NewFeature", "declaredAt": { "fileName": "ScreenRole.kt", "line": 7 }, "exception": "x.Y" },
              { "kind": "TemplatePreviewFailed", "message": "m", "detail": "a.B" },
              { "kind": "ExplanationFailed", "message": "m", "detail": null, "declaredAt": null, "exception": null }
            ]""",
        )

        val problems = parse(withSites).definition.problems

        assertEquals(listOf(DefinitionProblemKind.TemplateSetPreviewFailed, DefinitionProblemKind.TemplatePreviewFailed, DefinitionProblemKind.ExplanationFailed), problems.map { it.kind })
        assertEquals(DeclarationSiteRef("ScreenRole.kt", 7), problems[0].declaredAt)
        assertEquals("x.Y", problems[0].exception)
        assertEquals(listOf(null, null), problems.drop(1).map { it.declaredAt })
        assertEquals(listOf(null, null), problems.drop(1).map { it.exception })
    }

    @Test
    fun `templates の部分木は従来のテンプレート読みで読まれる`() {
        val middle = parsed.templates.single { it.summary.template == "a.b.Middle" }
        assertEquals(listOf("name"), middle.summary.captureNames)
        assertEquals(definition.roles.map { it.qualifiedName }, parsed.templates.map { it.summary.template })
    }

    @Test
    fun `generatedAt が時刻でない文字列なら Incompatible でどこかを示す`() {
        val failure = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replaceFirst("2026-10-04T00:30:12Z", "<generatedAt>"))
        assertEquals("generatedAt", failure.location)
        assertTrue(failure.expected, "ISO-8601" in failure.expected)
        assertEquals("string", failure.actual)
    }

    @Test
    fun `katachi が書いた fixture の generatedAt と katachiVersion は決まった実値`() {
        for (name in DefinitionFixtures.definitionNames().filter { it.startsWith("synthetic-") }) {
            val definition = DefinitionFixtures.definition(name)
            assertEquals(name, Instant.parse("2026-10-04T00:30:12Z"), definition.generatedAt)
            assertEquals(name, "0.3.0", definition.katachiVersion)
        }
    }

    @Test
    fun `module の block が注入した entry は synthetic と place の旗を持ち 旗の無い古い JSON は false として読む`() {
        val wildcard = moduleCapture.roles.single { it.qualifiedName == "other.Wildcard" }
        assertEquals(
            listOf(
                Triple("feature/home", false, true),
                Triple("feature/home/build", true, false),
                Triple("feature/home/build.gradle.kts", true, false),
                Triple("feature/home/src", false, false),
            ),
            wildcard.layout.slice(1..4).map { Triple(it.pattern, it.synthetic, it.place) },
        )
        val withoutFlags = text.lines().filterNot { it.trimStart().startsWith("\"synthetic\":") || it.trimStart().startsWith("\"place\":") }
            .joinToString("\n").replace("\"matchedFilesTruncated\": false,", "\"matchedFilesTruncated\": false")
        val old = parse(withoutFlags).definition
        assertTrue(old.roles.flatMap { it.layout }.none { it.synthetic || it.place })
        // A flag that is there but is not a boolean is not "absent": the file is incompatible.
        val wrong = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replaceFirst("\"synthetic\": false", "\"synthetic\": \"no\""))
        assertEquals("roles[0].layout[0].synthetic", wrong.location)
    }

    @Test
    fun `知らないキーは無視され fileDeclarations が無い古い katachi の JSON は null として読む`() {
        val withExtra = text.replaceFirst("\"schemaVersion\": 1,", "\"schemaVersion\": 1,\n  \"future\": { \"x\": [1, 2] },")
        assertEquals(definition, parse(withExtra).definition)
        val explainedText = DefinitionFixtures.definitionText("synthetic-definition-explained")
        val oldKatachi = explainedText.replace("\"fileDeclarations\":", "\"fileDeclarationsRenamed\":")
        val roles = parse(oldKatachi).definition.roles
        assertTrue(roles.flatMap { it.constraints }.all { it.fileDeclarations == null })
        assertNull(roles.first().constraints.first().fileDeclarations)
    }

    @Test
    fun `schemaVersion が読める範囲に無ければ読まない`() {
        val failure = failureOf<KatachiUnsupportedDefinitionSchemaException>(text.replaceFirst("\"schemaVersion\": 1", "\"schemaVersion\": 2"))
        assertEquals(2, failure.found)
        assertEquals(listOf(1), failure.supported)
        assertTrue(failure.message.orEmpty(), "released together" in failure.message.orEmpty())
    }

    @Test
    fun `必須のキーが無いとどこかを示して読まない`() {
        val noKind = text.replaceFirst("\"kind\": \"Directory\"", "\"kindRenamed\": \"Directory\"")
        val failure = failureOf<KatachiIncompatibleDefinitionJsonException>(noKind)
        assertEquals("roles[0].layout[0].kind", failure.location)
        assertNull(failure.actual)
        val noSchema = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replaceFirst("\"schemaVersion\": 1,", ""))
        assertEquals("schemaVersion", noSchema.location)
    }

    @Test
    fun `型が違うキーは期待と実際の型を示して読まない`() {
        val failure = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replaceFirst("\"required\": false", "\"required\": \"no\""))
        assertEquals("roles[0].layout[0].required", failure.location)
        assertEquals("boolean", failure.expected)
        assertEquals("string", failure.actual)
        val badTime = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replaceFirst("\"generatedAt\": \"2026-10-04T00:30:12Z\"", "\"generatedAt\": 20261004"))
        assertEquals("generatedAt", badTime.location)
        assertEquals("string (ISO-8601 instant)", badTime.expected)
    }

    @Test
    fun `templates の部分木の欠けは templates 配下の場所で報告される`() {
        val failure = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replace("\"roleName\"", "\"roleNameRenamed\""))
        assertEquals("templates.templates[0].roleName", failure.location)
    }

    @Test
    fun `JSON でないものと空のファイルと途中で切れたものは Malformed`() {
        assertTrue(failureOf<KatachiMalformedDefinitionJsonException>("").problem.isNotEmpty())
        failureOf<KatachiMalformedDefinitionJsonException>("not json")
        failureOf<KatachiMalformedDefinitionJsonException>(text.take(text.length / 2))
    }

    @Test
    fun `配列や数値など object でない文書は Incompatible`() {
        failureOf<KatachiIncompatibleDefinitionJsonException>("[]")
    }

    @Test
    fun `例外の文面は英語で ASCII だけで直し方を言う`() {
        val message = failureOf<KatachiIncompatibleDefinitionJsonException>(text.replace("\"roleName\"", "\"x\"")).message.orEmpty()
        assertTrue(message, message.all { it.code < 0x80 })
        assertTrue(message, "released together" in message)
    }

    @Test
    fun `captures の wildcardIndex と transform は katachi が書けば読み 書かない古い JSON では 0 と null になる`() {
        // The hand-written fixture is from before the two keys.
        val old = future.roles.flatMap { it.layout }.flatMap { it.captures }
        assertTrue(old.isNotEmpty())
        assertTrue(old.all { it.wildcardIndex == 0 && it.transform == null })

        // The first capture katachi wrote, with both keys changed.
        val json = text.replaceFirst(""""wildcardIndex": 0""", """"wildcardIndex": 1""").replaceFirst(""""transform": null""", """"transform": "pascalCase"""")
        val changed = parse(json).definition.roles.flatMap { it.layout }.flatMap { it.captures }.first()
        assertEquals(1, changed.wildcardIndex)
        assertEquals("pascalCase", changed.transform)
    }
}
