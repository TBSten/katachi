package me.tbsten.katachi.intellij.testing

import me.tbsten.katachi.intellij.data.json.JsonValue
import me.tbsten.katachi.intellij.data.json.ParsedDefinitionJson
import me.tbsten.katachi.intellij.data.json.parseDefinitionJson
import me.tbsten.katachi.intellij.data.json.parseJsonText
import me.tbsten.katachi.intellij.model.DefinitionModel
import java.io.File
import java.nio.file.Path
import java.nio.file.Paths

/** One line of a `contract/glob` JSON file: a pattern and a path with the answer, or a pattern that must not compile. */
internal data class GlobCase(
    val pattern: String,
    val path: String?,
    val matches: Boolean?,
    val error: Boolean,
    /** The pattern's literal leading levels, when the file records them (the generated one does). */
    val literalPrefix: List<String>? = null,
    val hasWildcard: Boolean? = null,
)

/**
 * The definition contract under `src/test/resources/contract/`: the JSON files of `definition`
 * and `glob`, and a SARIF file among `json`. The `synthetic-definition-*.json` and `glob/glob-cases.json` are
 * generated from katachi itself (`:katachi:test`, `KATACHI_UPDATE_IDE_PLUGIN_FIXTURES=true`). The only
 * `handwritten-*` file holds what katachi's own tests cannot write (the Konsist backends, values from a newer katachi).
 * Every test over [definitionNames] and [globCaseFiles] covers both.
 *
 * ```kotlin
 * for (name in DefinitionFixtures.definitionNames()) check(DefinitionFixtures.definition(name))
 * ```
 */
internal object DefinitionFixtures {
    private fun text(path: String): String {
        val stream = DefinitionFixtures::class.java.getResourceAsStream("/contract/$path")
            ?: throw IllegalArgumentException("No test resource /contract/$path")
        return stream.use { String(it.readBytes(), Charsets.UTF_8) }
    }

    fun definitionText(name: String): String = text("definition/$name.json")

    fun path(name: String): Path = Paths.get("/fixture/definition/$name.json")

    fun parsed(name: String): ParsedDefinitionJson = parseDefinitionJson(definitionText(name), path(name))

    fun definition(name: String): DefinitionModel = parsed(name).definition

    /** The names (without `.json`) of every definition fixture, hand-written and generated. */
    fun definitionNames(): List<String> = namesIn("definition", ".json")

    /** A SARIF file kept with the JSON goldens (a SARIF file is JSON): `json/<name>.json`. */
    fun sarifText(name: String): String = text("json/$name.json")

    /** The glob case files that exist (`glob-cases`, generated by katachi). */
    fun globCaseFiles(): List<String> = namesIn("glob", ".json")

    fun globCases(name: String): List<GlobCase> {
        val array = parseJsonText(text("glob/$name.json"), Paths.get("/fixture/glob/$name.json")) as? JsonValue.JsonArray
            ?: throw IllegalArgumentException("contract/glob/$name.json is not an array")
        return array.elements.map { element ->
            val members = (element as? JsonValue.JsonObject)?.members ?: throw IllegalArgumentException("not an object: $element")
            GlobCase(
                pattern = (members["pattern"] as? JsonValue.JsonString)?.value ?: throw IllegalArgumentException("no pattern: $element"),
                path = (members["path"] as? JsonValue.JsonString)?.value,
                matches = (members["matches"] as? JsonValue.JsonBoolean)?.value,
                error = (members["error"] as? JsonValue.JsonBoolean)?.value == true,
                literalPrefix = (members["literalPrefix"] as? JsonValue.JsonArray)?.elements
                    ?.map { (it as? JsonValue.JsonString)?.value ?: throw IllegalArgumentException("not a string: $it") },
                hasWildcard = (members["hasWildcard"] as? JsonValue.JsonBoolean)?.value,
            )
        }
    }

    private fun namesIn(directory: String, suffix: String): List<String> {
        val url = DefinitionFixtures::class.java.getResource("/contract/$directory")
            ?: throw IllegalArgumentException("No test resource directory /contract/$directory")
        val files = File(url.toURI()).list().orEmpty()
        return files.filter { it.endsWith(suffix) }.map { it.removeSuffix(suffix) }.sorted()
    }
}
