package me.tbsten.katachi.test.architecture

import io.kotest.assertions.withClue
import io.kotest.core.spec.style.FreeSpec
import io.kotest.matchers.shouldBe
import java.io.File
import me.tbsten.katachi.ExperimentalKatachiApi
import me.tbsten.katachi.InternalKatachiApi
import me.tbsten.katachi.dsl.files.internal.RealFileSystem
import me.tbsten.katachi.dsl.files.internal.findProjectRoot

/**
 * `processor` and `check` sit in one layer, so `LayerImports` lets either import the other
 * freely. This records every import between the two as committed text: a new one shows up
 * as a diff to review, not as a dependency that quietly grew.
 */
class LayerImportSnapshotSpec : FreeSpec({
    "processor と check の間の import が、記録したスナップショットと一致する" {
        val actual = renderSnapshot(crossImports())
        val file = snapshotFile()

        when {
            updateRequested() -> file.write(actual)
            !file.isFile -> {
                file.write(actual)
                throw AssertionError(
                    "${file.path} did not exist, so it was created with the current content. Review the diff and run again.",
                )
            }
            else -> withClue(
                "processor と check の間の import が変わった。意図した変更なら " +
                    "`./gradlew :architecture-test:test -D$UPDATE_PROPERTY=true` でスナップショットを更新する",
            ) {
                actual shouldBe file.readText()
            }
        }
    }

    "スナップショットは両方向に 1 件以上ある" {
        // The two depend on each other today. A snapshot that lost one direction entirely is
        // worth a look at the spec, not a silent pass with half the file empty.
        val directions = crossImports().map { it.direction }.toSet()
        directions shouldBe setOf("$PROCESSOR -> $CHECK", "$CHECK -> $PROCESSOR")
    }
})

private const val UPDATE_PROPERTY: String = "katachi.snapshot.update"

private const val SNAPSHOT_PATH: String = "architecture-test/snapshots/layer-imports.txt"

private const val MAIN_SOURCES: String = "katachi/src/main/kotlin/me/tbsten/katachi"

private const val PROCESSOR: String = "processor"

private const val CHECK: String = "check"

private val HEADER: List<String> = listOf(
    "# Snapshot of the imports between katachi's processor and check packages. Do not edit by hand.",
    "# Generated by: LayerImportSnapshotSpec in architecture-test",
    "# Update: ./gradlew :architecture-test:test -D$UPDATE_PROPERTY=true",
    "# One line = <from -> to> TAB <importing file> TAB <imported declaration>",
)

private class CrossImport(val direction: String, val file: String, val imported: String)

private fun updateRequested(): Boolean = System.getProperty(UPDATE_PROPERTY) == "true"

private fun File.write(text: String) {
    parentFile.mkdirs()
    writeText(text)
}

@OptIn(InternalKatachiApi::class, ExperimentalKatachiApi::class)
private fun projectRoot(): File = File(findProjectRoot(RealFileSystem()).path.value)

private fun crossImports(): List<CrossImport> {
    val root = projectRoot()
    val sources = File(root, MAIN_SOURCES)
    return listOf(PROCESSOR to CHECK, CHECK to PROCESSOR).flatMap { (from, to) ->
        val importOfOther = Regex("""^import me\.tbsten\.katachi\.$to\.(\S+)""")
        File(sources, from).walkTopDown()
            .filter { it.isFile && it.extension == "kt" }
            .flatMap { file ->
                file.readLines().mapNotNull { line ->
                    importOfOther.find(line)?.let { match ->
                        CrossImport("$from -> $to", file.toRelativeString(root).replace(File.separatorChar, '/'), match.groupValues[1])
                    }
                }
            }
            .toList()
    }
}

private fun renderSnapshot(imports: List<CrossImport>): String {
    val lines = imports.map { "${it.direction}\t${it.file}\t${it.imported}" }.sorted()
    return (HEADER + lines).joinToString(separator = "\n", postfix = "\n")
}

private fun snapshotFile(): File = File(projectRoot(), SNAPSHOT_PATH)
